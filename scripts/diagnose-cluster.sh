PROBE3
codefence "$P3_OUT"
FIRST_KEY="$(grep -E '^FIRST_KEY_FOR_PROBE7=' "$P3_OUT" | tail -n1 | sed 's/^FIRST_KEY_FOR_PROBE7=//' || true)"
log "probe 3: sample key for probe 7 = ${FIRST_KEY:-<none-found>}"

