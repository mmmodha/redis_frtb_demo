# ===================================================================
# ROOT CAUSE — rule-based classification from the probe outputs
# ===================================================================
# Hypotheses (carried over from Wave 5.13 spec + smoke-run-6 SUMMARY):
#   A — TAG schema/payload casing mismatch (data shape vs schema attrs)
#   B — Cluster-aware FT.SEARCH fan-out missing across shards
#   C — Index visibility / proxy single-shard routing
#   D — data lives at a different JSON path than the schema declares
#         (e.g. nested under a wrapper) — keys present but $.risk_class
#         resolves to nothing for the indexer
#   E — index metadata is stale or corrupt: FT.INFO num_docs > 0 on every
#         shard but FT.SEARCH * returns 0 on every shard, and a sampled
#         doc has the expected shape - the index counter survived but its
#         posting lists are empty (partial recovery after an OOM during
#         FT.CREATE / module reload).
#
# Decision rules (mechanical, transparent):
#   - SANITY_VIA_CLUSTER  = total from "* LIMIT 0 0" via Cluster client (probe 5)
#   - SUM_DIRECT          = sum of per-shard FT.SEARCH "*" totals     (probe 4)
#   - NUM_DOCS_TOTAL      = sum of num_docs across masters             (probe 2)
#   - TAG_HITS_VIA_CLUSTER = max of the 5 specific-tag queries        (probe 5)
#   - TAG_HITS_DIRECT      = whether any per-shard direct redis-cli FT.SEARCH
#                            on a specific tag returned > 0           (probe 6)
#   - SAMPLE_HAS_RISK_CLASS = the sample key's parsed JSON contains risk_class
#                            with non-empty value                     (probes 3/7)

extract_total() {
  # Pulls a numeric total from a "label=... total=N" line. Pipefail-safe.
  local file="$1" label="$2" line
  line="$(grep -E "^${label} " "$file" 2>/dev/null | sed -n '1p' || true)"
  if [[ "$line" =~ total=([0-9]+) ]]; then
    echo "${BASH_REMATCH[1]}"
  else
    echo "0"
  fi
}

SANITY_VIA_CLUSTER="$(extract_total "$P5_OUT" sanity)"
TAG_HITS_VIA_CLUSTER=0
for L in risk_GIRR risk_girr stype_DELTA stype_Delta bucket_1; do
  V="$(extract_total "$P5_OUT" "$L")"
  V="${V:-0}"
  [[ "$V" -gt "$TAG_HITS_VIA_CLUSTER" ]] && TAG_HITS_VIA_CLUSTER="$V"
done

