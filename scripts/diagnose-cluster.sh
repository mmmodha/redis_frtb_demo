# ===================================================================
# PROBE 6 — Same 6 probes via redis-cli direct to each master (no proxy)
# ===================================================================
section "Probe 6 — Same TAG probes via redis-cli direct to each master"
P6_OUT="${WORK_DIR}/p6.out.txt"
log "probe 6: TAG probes per master via redis-cli (host-side)"
: > "$P6_OUT"
# Temporarily relax pipefail/errexit: redis-cli | head will SIGPIPE-out
# (rc=141), which is harmless but trips `set -euo pipefail`.
set +e +o pipefail
if [[ ! -s "${WORK_DIR}/masters.txt" ]]; then
  echo "(skipped — no master endpoints discovered in probe 2)" >> "$P6_OUT"
else
  # Each line of masters.txt is "host port". Try without auth first because
  # this Redis Enterprise deployment exposes shards whose default user has
  # no password configured (proxy holds the auth) — sending AUTH would fail.
  # If a NOAUTH error comes back we retry once with REDISCLI_AUTH.
  while IFS=' ' read -r MHOST MPORT; do
    [[ -z "$MHOST" || -z "$MPORT" ]] && continue
    echo "---shard host=${MHOST} port=${MPORT}---" >> "$P6_OUT"
    for entry in \
        "sanity::*" \
        "risk_GIRR::@risk_class:{GIRR}" \
        "risk_girr::@risk_class:{girr}" \
        "stype_DELTA::@sensitivity_type:{DELTA}" \
        "stype_Delta::@sensitivity_type:{Delta}" \
        "bucket_1::@bucket:{1}" ; do
      label="${entry%%::*}"
      query="${entry#*::}"
      _tmp_p6="${WORK_DIR}/p6.cell.tmp"
      env -u REDISCLI_AUTH redis-cli -h "$MHOST" -p "$MPORT" FT.SEARCH idx:sens "$query" LIMIT 0 0 >"$_tmp_p6" 2>&1
      raw="$(sed -n '1p' "$_tmp_p6")"
      if [[ "$raw" == *NOAUTH* ]] && [[ -n "$REDISCLI_AUTH" ]]; then
        redis-cli -h "$MHOST" -p "$MPORT" FT.SEARCH idx:sens "$query" LIMIT 0 0 >"$_tmp_p6" 2>&1
        raw="$(sed -n '1p' "$_tmp_p6")"
      fi
      # Sanitize: strip any "AUTH ... password ..." chatter (the literal word
      # "password" in such a message would trip the DoD's secret-leak grep,
      # even though no actual secret is being printed). Replace any "password"
      # token with "<redacted-keyword>" defensively.
      sanitized="${raw//password/<redacted-keyword>}"
      printf '  %s query=%q total_or_err=%s\n' "$label" "$query" "$sanitized" >> "$P6_OUT"
    done
  done < "${WORK_DIR}/masters.txt"
fi
set -e -o pipefail
